import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
import {join} from 'node:path';
import {chromium} from './helpers/browser.mjs';
import {createMobileFixture} from './helpers/mobile-fixture.mjs';
import {developmentPaths} from '../scripts/workspace-paths.mjs';

const artifacts=join(developmentPaths().artifacts,'mobile-settings');

test('mobile settings have independent pages, working choices and stable Back, Forward and playback return', {timeout:90000}, async t=>{
  const fixture=await createMobileFixture({preview:true}),browser=await chromium.launch({headless:true});
  t.after(async()=>{await browser.close();await fixture.close();});
  const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true});page.setDefaultTimeout(8000);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));mkdirSync(artifacts,{recursive:true});
  await page.goto(fixture.base);
  const nav=page.getByRole('navigation',{name:'手机导航',exact:true});await nav.waitFor();
  await page.evaluate(()=>{window.__mobileSettingsAudio=document.querySelector('audio');});
  await nav.getByRole('button',{name:'我的',exact:true}).click();
  await page.screenshot({path:join(artifacts,'profile-390.png')});
  await page.getByRole('button',{name:'音乐来源 来源开关与状态',exact:true}).click();
  const source=page.locator('[data-settings-section="sources"]:visible');await source.waitFor();
  assert.equal(await nav.count(),0);assert.equal(await page.locator('.settings-nav').count(),0);
  assert.equal(await page.locator('.mobile-header h1').textContent(),'音乐来源');
  assert.equal(await page.getByRole('button',{name:'搜索歌曲或视频',exact:true}).count(),0);
  await source.getByRole('button',{name:'关闭后的歌曲 变灰',exact:true}).click();
  let sheet=page.getByRole('dialog',{name:'关闭后的歌曲',exact:true});await sheet.waitFor();
  await page.goBack();await sheet.waitFor({state:'detached'});await source.waitFor();
  await source.getByRole('button',{name:'关闭后的歌曲 变灰',exact:true}).click();
  await sheet.getByRole('button',{name:'隐藏',exact:true}).click();
  await source.getByRole('button',{name:'关闭后的歌曲 隐藏',exact:true}).waitFor();
  assert.equal(fixture.sourceWrites.at(-1).youtube.disabledDisplay,'hide');
  await source.getByRole('switch',{name:'启用 YouTube',exact:true}).check();
  await page.waitForFunction(()=>document.querySelector('.mobile-source-settings')?.getAttribute('aria-busy')==='false');
  assert.equal(fixture.sourceWrites.at(-1).youtube.enabled,true);
  await page.screenshot({path:join(artifacts,'sources-390.png')});
  await page.getByRole('button',{name:'打开正在播放',exact:true}).click();
  await page.getByRole('button',{name:'返回浏览音乐',exact:true}).click();await source.waitFor();
  assert.equal(await page.evaluate(()=>window.__mobileSettingsAudio===document.querySelector('audio')),true,'settings and player share one audio instance');
  assert.equal(await page.locator('.mobile-header h1').textContent(),'音乐来源');
  await source.locator('summary').click();
  await source.getByRole('button',{name:'查看来源与许可说明',exact:true}).click();
  await page.locator('[data-settings-section="about"]:visible').waitFor();
  await page.getByRole('button',{name:'返回上一级',exact:true}).click();await source.waitFor();
  await page.reload();await source.waitFor();
  await page.evaluate(()=>{window.__mobileSettingsAudio=document.querySelector('audio');});
  assert.equal(await source.getByRole('switch',{name:'启用 YouTube',exact:true}).isChecked(),true);
  await page.goBack();await page.getByRole('region',{name:'我的',exact:true}).waitFor();
  await page.goForward();await source.waitFor();
  await page.getByRole('button',{name:'返回上一级',exact:true}).click();await nav.waitFor();
  await page.getByRole('button',{name:'外观与主题 明暗与配色',exact:true}).click();
  const appearance=page.locator('[data-settings-section="appearance"]:visible');await appearance.waitFor();
  await appearance.getByRole('button',{name:'白天',exact:true}).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  const palettes=appearance.getByRole('group',{name:'主题配色',exact:true});
  assert.equal(await page.getByRole('dialog').count(),0,'appearance choices stay on the page');
  for(const width of [320,360,390,430]) {
    await page.setViewportSize({width,height:844});
    const layout=await palettes.evaluate(e=>({overflow:e.scrollWidth>e.clientWidth,rows:[...e.querySelectorAll('button')].map(b=>b.getBoundingClientRect().toJSON())}));
    assert.equal(layout.overflow,false);assert.equal(layout.rows.length,4);
    layout.rows.forEach((row,index)=>{assert(row.height>=48);assert(row.width>=48);if(index>=2)assert(row.top>=layout.rows[index-2].bottom);});
    assert(layout.rows[1].left>=layout.rows[0].right);
  }
  for(const [label,value] of [['暖纸炭黑','paper'],['经典薄荷','mint'],['晴樱粉','ocean'],['珊瑚红','plum']]) {
    await palettes.getByRole('button',{name:label,exact:true}).click();
    assert.equal(await page.locator('html').getAttribute('data-palette'),value);
    assert.equal(await palettes.getByRole('button',{name:label,exact:true}).getAttribute('aria-pressed'),'true');
    assert.equal(await palettes.locator('[aria-pressed="true"]').count(),1);
  }
  await palettes.getByRole('button',{name:'经典薄荷',exact:true}).focus();
  await palettes.getByRole('button',{name:'经典薄荷',exact:true}).press('Enter');
  await page.reload();await appearance.waitFor();
  await page.evaluate(()=>{window.__mobileSettingsAudio=document.querySelector('audio');});
  assert.equal(await palettes.getByRole('button',{name:'经典薄荷',exact:true}).getAttribute('aria-pressed'),'true','inline choices persist after refresh');
  assert.equal(await appearance.getByRole('button',{name:'白天',exact:true}).getAttribute('aria-pressed'),'true');
  await page.screenshot({path:join(artifacts,'appearance-430.png')});
  await appearance.getByRole('button',{name:'欢迎页 背景图片与构图',exact:true}).click();
  const welcome=page.locator('[data-settings-section="welcome"]:visible');await welcome.waitFor();
  await welcome.locator('.welcome-preview-frame.mobile').waitFor();
  await page.getByRole('button',{name:'返回上一级',exact:true}).click();await appearance.waitFor();
  await page.getByRole('button',{name:'返回上一级',exact:true}).click();await nav.waitFor();
  await page.getByRole('button',{name:'启动与访问 进入方式与访问码',exact:true}).click();
  const current=page.getByLabel('当前访问码',{exact:true});await current.fill('draft-value');
  await page.evaluate(()=>window.scrollTo(0,180));
  await page.waitForFunction(()=>window.scrollY>100);
  const settingsScroll=await page.evaluate(()=>window.scrollY);
  await page.getByRole('button',{name:'打开正在播放',exact:true}).click();
  await page.goBack();assert.equal(await current.inputValue(),'draft-value','playback preserves the settings draft');
  await page.waitForFunction(top=>Math.abs(window.scrollY-top)<2,settingsScroll);
  assert.equal(await page.evaluate(()=>window.__mobileSettingsAudio===document.querySelector('audio')),true,'editing and returning from playback keep the same audio instance');
  await page.getByRole('button',{name:'返回上一级',exact:true}).click();await nav.waitFor();
  await page.getByRole('button',{name:'外观与主题 明暗与配色',exact:true}).click();
  await page.setViewportSize({width:1280,height:800});
  await page.locator('.settings-view').waitFor();
  assert.equal(await page.getByRole('dialog').count(),0);
  assert.equal(await page.locator('.settings-view').getByRole('button',{name:'经典薄荷',exact:true}).getAttribute('aria-pressed'),'true');
  await page.locator('.settings-nav').getByRole('button',{name:'音乐来源',exact:true}).click();
  await page.locator('.settings-view [data-settings-section="sources"]:visible').waitFor();
  assert.deepEqual(errors,[]);
});

test('mobile library opens playlist details and keeps selection and management in sheets', {timeout:60000},async t=>{
  const fixture=await createMobileFixture({preview:true}),browser=await chromium.launch({headless:true});
  t.after(async()=>{await browser.close();await fixture.close();});
  const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true});page.setDefaultTimeout(8000);
  await page.goto(fixture.base);await page.getByRole('navigation',{name:'手机导航',exact:true}).getByRole('button',{name:'音乐库',exact:true}).click();
  await page.locator('.mobile-library').getByRole('button',{name:'我的收藏 2 首歌曲',exact:true}).click();
  const library=page.locator('.song-library-page');
  const first=await library.locator('.song-library-row').first().boundingBox();assert(first.y<330,'songs start in the upper half of the phone');
  assert.equal(await library.getByRole('button',{name:'资料库维护',exact:true}).count(),0);
  await library.getByRole('button',{name:'选择歌单',exact:true}).click();
  await page.getByRole('dialog',{name:'选择歌单',exact:true}).getByRole('button',{name:'晚风与散步 2 首',exact:true}).click();
  await library.getByRole('heading',{name:'晚风与散步',exact:true}).waitFor();
  await library.getByRole('button',{name:'歌单管理',exact:true}).click();
  await page.getByRole('dialog',{name:'歌单管理',exact:true}).getByRole('button',{name:'歌单改名',exact:true}).click();
  await page.getByRole('dialog',{name:'歌单改名',exact:true}).getByRole('textbox',{name:'歌单名称',exact:true}).fill('晚风散步');
  await page.goBack();await page.getByRole('dialog',{name:'歌单改名',exact:true}).waitFor({state:'detached'});
  await library.getByRole('button',{name:'选择歌单',exact:true}).waitFor();
  assert.equal(await page.getByRole('dialog').count(),0,'a replaced management sheet does not remain in Back history');
  mkdirSync(artifacts,{recursive:true});await page.screenshot({path:join(artifacts,'library-390.png')});
});
