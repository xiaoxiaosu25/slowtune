test('desktop chart favorites reflect saved membership, pending writes, retry and reload across chart sources', { timeout: 60000 }, async t => {
  const fixture = await startSongManagementFixture({ clientRoot: process.env.FAVORITE_TEST_CLIENT_ROOT }); t.after(fixture.close);
  const browser = await chromium.launch({ channel: 'msedge', headless: true }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }), errors = [], writes = [];
  page.setDefaultTimeout(8000); page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => new URL(route.request().url()).origin === fixture.origin ? route.continue() : route.abort());
  await page.route('**/api/charts*', route => {
    const query = new URL(route.request().url()).searchParams;
    return route.fulfill({ json: { source: query.get('source'), chart: query.get('chart'), title: '测试热歌榜', sourceUrl: 'https://example.com/charts', fetchedAt: Date.now(), items: [{ rank: 1, title: '晴天', artists: ['周杰伦'] }] } });
  });
  let failWrite = false, release, metadataReads = 0, gate;
  t.after(() => release?.());
  await page.route('**/api/song-library/chart-favorites', async route => {
    writes.push(route.request().postDataJSON());
    if (gate) await gate;
    return failWrite ? route.fulfill({ status: 503, json: { error: { code: 'storage' } } }) : route.continue();
  });
  page.on('request', request => { if (request.url().endsWith('/v1/call/metadata')) metadataReads++; });
  const initial = fixture.library.read().snapshot, count = initial.favorites.length;
  await page.goto(fixture.origin); await navigate(page, '音乐榜单');
  const heart = () => page.getByRole('button', { name: /^(取消收藏|收藏)榜单歌曲 晴天$/ });
  const savedResponse = page.waitForResponse(response => response.url().endsWith('/api/song-library/chart-favorites'));
  await heart().click(); assert.equal((await savedResponse).status(), 200);
  assert.equal(fixture.library.read().snapshot.favorites.length, count + 1);
  assert.equal(fixture.library.read().snapshot.versions.length, initial.versions.length);
  await page.waitForFunction(() => document.querySelector('.chart-song [aria-pressed="true"]'));
  assert.equal(await heart().getAttribute('aria-label'), '取消收藏榜单歌曲 晴天');
  await page.reload(); await navigate(page, '音乐榜单'); assert.equal(await heart().getAttribute('aria-pressed'), 'true');
  await heart().click(); await page.waitForFunction(() => document.querySelector('.chart-song [aria-pressed="false"]'));
  assert.equal(fixture.library.read().snapshot.favorites.length, count);
  gate = new Promise(resolve => { release = resolve; }); failWrite = true;
  await heart().click(); assert.equal(await heart().getAttribute('aria-busy'), 'true'); assert.equal(await heart().isDisabled(), true);
  release(); gate = undefined; await page.locator('.desktop-operation-feedback').getByRole('alert').waitFor();
  assert.equal(await heart().getAttribute('aria-pressed'), 'false'); assert.equal(await heart().isEnabled(), true);
  gate = new Promise(resolve => { release = resolve; }); failWrite = false;
  await page.getByRole('button', { name: '重试保留编辑', exact: true }).click(); assert.equal(await heart().getAttribute('aria-busy'), 'true');
  release(); gate = undefined; await page.waitForFunction(() => document.querySelector('.chart-song [aria-pressed="true"]'));
  assert.equal(fixture.library.read().snapshot.favorites.length, count + 1);
  assert.equal(writes.length, 3, 'failed writes retry once and saved songs are removed through edits');
  await page.getByRole('tab', { name: 'QQ', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.charts-page[data-chart-source="qq"] .chart-song [aria-pressed="false"]'));
  await heart().click(); await page.waitForFunction(() => document.querySelector('.chart-song [aria-pressed="true"]'));
  assert.equal(fixture.library.read().snapshot.favorites.length, count + 2);
  await page.getByRole('tab', { name: '网易云', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.charts-page[data-chart-source="netease"] .chart-song [aria-pressed="true"]'));
  assert.equal(metadataReads, 0); assert.equal(await page.locator('audio').evaluate(audio => audio.paused && !audio.getAttribute('src')), true);
  assert.deepEqual(errors, []);
});

test('desktop favorite shows pending and saved feedback inside search, ignores repeated clicks, and supports retry', { timeout: 60000 }, async t => {
  const fixture = await startSongManagementFixture({ clientRoot: process.env.FAVORITE_TEST_CLIENT_ROOT }); t.after(fixture.close);
  const browser = await chromium.launch({ channel: 'msedge', headless: true }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }), errors = [];
  page.setDefaultTimeout(8000); page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => new URL(route.request().url()).origin === fixture.origin ? route.continue() : route.abort());
  let release, requested, failWrite = false, writes = 0, metadataReads = 0;
  const metadataGate = new Promise(resolve => { release = resolve; }); t.after(() => release());
  const metadataRequested = new Promise(resolve => { requested = resolve; });
  await page.route('**/v1/call/metadata', async route => {
    metadataReads++; requested(); await metadataGate; await route.continue().catch(() => {});
  });
  await page.route('**/api/song-library/sources', route => {
    writes++;
    return failWrite ? route.fulfill({ status: 503, json: { error: { code: 'storage' } } }) : route.continue();
  });
  await page.goto(fixture.origin); await page.getByRole('button', { name: '开始搜索', exact: true }).click();
  const search = page.getByRole('dialog', { name: '搜索音乐', exact: true });
  await search.getByLabel('弹窗搜索关键词').fill('晴天'); await search.getByRole('button', { name: '搜索', exact: true }).click();
  const favorite = search.getByRole('button', { name: '收藏 晴天 · 2026音乐会', exact: true });
  await favorite.click(); await metadataRequested;
  assert.equal(await favorite.getAttribute('aria-busy'), 'true', 'the clicked heart immediately acknowledges metadata loading');
  assert.equal(await favorite.isDisabled(), true, 'a repeated click cannot cancel the first favorite');
  assert.equal(writes, 0);
  failWrite = true; release(); await search.getByRole('alert').waitFor();
  assert.equal(writes, 1); assert.equal(await favorite.isEnabled(), true);
  assert(!fixture.library.read().snapshot.versions.some(version => version.ref.id === 'BV0000000006'));
  failWrite = false; await search.getByRole('button', { name: '重试保留编辑', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.search-modal [aria-label="收藏 晴天 · 2026音乐会"]')?.getAttribute('aria-pressed') === 'true');
  await search.getByRole('status').filter({ hasText: '已处理 1 项' }).waitFor();
  assert.equal(await page.locator('.app>.toast').count(), 0, 'saved feedback stays in the active dialog');
  assert.equal(writes, 2); assert.equal(metadataReads, 1);
  const snapshot = fixture.library.read().snapshot, version = snapshot.versions.find(version => version.ref.id === 'BV0000000006');
  assert(snapshot.favorites.some(favorite => favorite.songId === version.songId));
  await favorite.click(); await page.waitForFunction(() => document.querySelector('.search-modal [aria-label="收藏 晴天 · 2026音乐会"]')?.getAttribute('aria-pressed') === 'false');
  await search.getByRole('status').filter({ hasText: '已取消收藏本首' }).waitFor();
  await search.getByRole('button', { name: '关闭', exact: true }).click();
  await page.reload(); await page.locator('.app').waitFor();
  assert(!fixture.library.read().snapshot.favorites.some(favorite => favorite.songId === version.songId));
  assert.deepEqual(errors, []);
});

test('desktop card and current-player hearts show pending until the library commits without interrupting audio', { timeout: 60000 }, async t => {
  const fixture = await startSongManagementFixture(); t.after(fixture.close);
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--autoplay-policy=no-user-gesture-required'] }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } }); page.setDefaultTimeout(8000);
  await page.route('**/*', route => new URL(route.request().url()).origin === fixture.origin ? route.continue() : route.abort());
  const track = { ...entry(ref(6)), title: '待收藏的歌曲', durationSeconds: 60 }, count = fixture.library.read().snapshot.favorites.length;
  await page.route('**/api/discovery/bilibili*', route => route.fulfill({ json: [{ id: 'music-recommendation', title: '音乐推荐', kind: 'recommendation', page: { items: [track] } }] }));
  let releaseMetadata, releaseWrite, sourceWrites = 0;
  const metadataGate = new Promise(resolve => { releaseMetadata = resolve; }); t.after(() => releaseMetadata());
  await page.route('**/v1/call/metadata', async route => { await metadataGate; await route.continue().catch(() => {}); });
  await page.route('**/api/song-library/sources', route => { sourceWrites++; return route.continue(); });
  await page.goto(fixture.origin);
  const cardHeart = page.locator('.music-card').getByRole('button', { name: '收藏 待收藏的歌曲', exact: true });
  await cardHeart.click();
  assert.equal(await cardHeart.getAttribute('aria-busy'), 'true'); assert.equal(await cardHeart.isDisabled(), true);
  assert.equal(sourceWrites, 0); releaseMetadata();
  await page.waitForFunction(() => document.querySelector('.cover-favorite')?.getAttribute('aria-pressed') === 'true');
  assert.equal(sourceWrites, 1); assert.equal(fixture.library.read().snapshot.favorites.length, count + 1);
  await page.getByRole('button', { name: '播放 待收藏的歌曲', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('audio')?.currentTime > .2);
  const before = await page.locator('audio').evaluate(audio => ({ src: audio.currentSrc, time: audio.currentTime }));
  const writeGate = new Promise(resolve => { releaseWrite = resolve; }); t.after(() => releaseWrite());
  await page.route('**/api/song-library/edits', async route => { await writeGate; await route.continue().catch(() => {}); });
  const playerHeart = page.getByRole('button', { name: '收藏当前歌曲', exact: true });
  await playerHeart.click(); assert.equal(await playerHeart.getAttribute('aria-busy'), 'true');
  assert.equal(await playerHeart.isDisabled(), true); assert.equal(fixture.library.read().snapshot.favorites.length, count + 1);
  releaseWrite(); await page.waitForFunction(() => document.querySelector('.playbar-heart')?.getAttribute('aria-pressed') === 'false');
  assert.equal(await playerHeart.isEnabled(), true); assert.equal(fixture.library.read().snapshot.favorites.length, count);
  await page.waitForFunction(time => document.querySelector('audio')?.currentTime > time, before.time);
  const after = await page.locator('audio').evaluate(audio => ({ src: audio.currentSrc, paused: audio.paused }));
  assert.equal(after.src, before.src); assert.equal(after.paused, false);
});
