import { cpSync, mkdirSync, existsSync, symlinkSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { desktopBuildDirectory, assertDesktopBuildDirectory } from './workspace-paths.mjs';
const root = fileURLToPath(new URL('..', import.meta.url)), target = desktopBuildDirectory(root);
const run = (script, args = []) => execFileSync(process.execPath, [join(root, script), ...args], { cwd: root, stdio: 'inherit', windowsHide: true });
run('scripts/check-docs.mjs'); run('scripts/generate-notices.mjs'); run('node_modules/typescript/bin/tsc', ['--noEmit']);
assertDesktopBuildDirectory(target, root);
mkdirSync(dirname(target), { recursive: true });
assertDesktopBuildDirectory(target, root);
rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
run('node_modules/vite/bin/vite.js', ['build', '--outDir', join(target, 'dist/client')]);
run('node_modules/typescript/bin/tsc', ['-p', 'tsconfig.server.json', '--outDir', join(target, 'dist/server')]);
for (const file of ['package.json', 'package-lock.json']) cpSync(join(root, file), join(target, file));
mkdirSync(join(target, 'scripts'), { recursive: true });
for (const name of ['launch.mjs', 'start.mjs', 'instance-path.mjs', 'control.mjs']) cpSync(join(root, 'scripts', name), join(target, 'scripts', name));
if (!existsSync(join(target, 'node_modules'))) symlinkSync(join(root, 'node_modules'), join(target, 'node_modules'), 'junction');
console.log('桌面专用构建：' + target);
